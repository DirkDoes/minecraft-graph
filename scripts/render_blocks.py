"""Bake inventory-less blocks from actual default block states and static textures."""
import hashlib
import json
from pathlib import Path

import numpy as np
from PIL import Image
from render_icons import Renderer, SIZE, raster_triangle, rotation, rgb

ROOT = Path(__file__).resolve().parents[1]


def matches(condition, state):
    if "OR" in condition:
        return any(matches(child, state) for child in condition["OR"])
    if "AND" in condition:
        return all(matches(child, state) for child in condition["AND"])
    return all(state.get(key) in value.split("|") for key, value in condition.items())


def select_models(definition, state):
    if "variants" in definition:
        entries = [value for key, value in definition["variants"].items()
                   if matches(dict(part.split("=", 1) for part in key.split(",") if part), state)]
    else:
        entries = [part["apply"] for part in definition["multipart"] if matches(part.get("when", {}), state)]
    return [entry[0] if isinstance(entry, list) else entry for entry in entries]


def render_block(renderer, block_id, state):
    slug = block_id.split(":")[1]
    entries = select_models(renderer.load_json(f"assets/minecraft/blockstates/{slug}.json"), state)
    faces = []
    for entry in entries:
        model = renderer.model(entry["model"])
        # Fluid meshes are generated by the game rather than stored in block JSON.
        if slug in ("water", "lava"):
            cube = renderer.model("minecraft:block/cube_all")
            model = {**cube, "textures": {**cube["textures"], "all": f"minecraft:block/{slug}_still"}}
        transform = rotation([entry.get("x", 0), entry.get("y", 0), 0])
        for points, uv, normal, texture, color in renderer.block_faces(model, [np.array([.48, .72, .32])]):
            if slug == "water":
                water_color = renderer.load_json("data/minecraft/worldgen/biome/plains.json")["effects"]["water_color"]
                color = rgb(int(water_color.removeprefix("#"), 16))
            points = (points - 8) @ transform.T
            normal = transform @ normal
            faces.append((points, uv, normal, texture, color))
    if not faces:
        raise ValueError(f"No block geometry for {block_id}")
    camera = rotation([30, 225, 0])
    projected_faces = [(points @ camera.T, uv, camera @ normal, texture, color) for points, uv, normal, texture, color in faces]
    bounds = np.concatenate([face[0] for face in projected_faces])
    center = (bounds.min(axis=0) + bounds.max(axis=0)) / 2
    scale = (SIZE - 8) / max(np.ptp(bounds[:, 0]), np.ptp(bounds[:, 1]))
    output = np.zeros((SIZE, SIZE, 4), dtype=np.uint8)
    depth = np.full((SIZE, SIZE), -np.inf)
    for points, uv, normal, texture, color in sorted(projected_faces, key=lambda face: face[0][:, 2].mean()):
        if normal[2] < -1e-6:
            continue
        points = (points - center) * scale
        screen = np.column_stack((SIZE / 2 + points[:, 0], SIZE / 2 - points[:, 1], points[:, 2]))
        shade = .65 + .35 * max(0, normal[1])
        for indices in ([0, 1, 2], [0, 2, 3]):
            raster_triangle(output, depth, screen[indices], uv[indices], texture, color * shade)
    image = Image.fromarray(output)
    if image.getbbox() is None:
        raise ValueError(f"Empty block icon for {block_id}")
    return image, entries


def main():
    graph = json.loads((ROOT / "data/graph.json").read_text(encoding="utf-8"))
    states = json.loads((ROOT / ".cache/generated/reports/blocks.json").read_text(encoding="utf-8"))
    renderer = Renderer(ROOT / ".cache/client.jar", ROOT / ".cache/special-models.json")
    output = ROOT / "assets/blocks"
    output.mkdir(parents=True, exist_ok=True)
    records = {}
    for node in graph["nodes"]:
        if node["kind"] != "block":
            continue
        block_id = node["blockId"]
        default = next(state for state in states[block_id]["states"] if state.get("default"))
        image, entries = render_block(renderer, block_id, default.get("properties", {}))
        image.save(output / (block_id.split(":")[1] + ".png"))
        records[block_id] = {"state": default.get("properties", {}), "models": entries}
    report = {"version": graph["version"], "clientSha1": hashlib.sha1((ROOT / ".cache/client.jar").read_bytes()).hexdigest(),
              "count": len(records), "blocks": records, "sourceTextures": sorted(renderer.used_textures),
              "limitations": ["Static default block state and first animation frame; one deterministic model alternative.",
                              "Plant biome tint uses representative green. Fluids use their real still texture on a simplified cube; Water uses the game's Plains water tint."]}
    (output / "coverage.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(f"Rendered {len(records)} real block icons")


if __name__ == "__main__":
    main()
